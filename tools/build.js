#!/usr/bin/env node
// Builds the behaviour pack and the .mcaddon.
//
//   node tools/build.js [--java <Java repo folder>] [--ref <git ref>]
//
// The gazebo comes from the Java edition's repo (gabmaybelle/spawn-gazebo) at the ref in
// java-source.json: its own generator (tools/generate-spawn.js) makes every wood and palette, and
// each is written here as a Bedrock structure file, so both editions share one design. The icon
// comes from there too. Output:
//   src/templates.ts, test/expected.ts   generated lists the scripts import (never edited by hand)
//   build/packs/bp                       the behaviour pack
//   build/packs/bp-test                  the self-test pack (test worlds only, never shipped)
//   build/mapping.txt                    every Java block state and what it became on Bedrock
//   dist/SpawnGazebo-<version>.mcaddon
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const { zip } = require('./zip.js');
const { javaRepo, javaGenerator, ASSETS } = require('./java-source.js');
const { templates, SIZE } = require('./templates.js');
const { mcstructure } = require('./mcstructure.js');
const { map } = require('./bedrock-map.js');

const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const out = path.join(root, 'build', 'packs');
const writeFile = (p, data) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, data); };
const writeJson = (p, obj) => writeFile(p, JSON.stringify(obj, null, '\t') + '\n');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const fail = (why) => { console.error('build failed: ' + why); process.exit(1); };

// The manifests carry the version from package.json and the script module versions the typings were
// installed at.
function manifest(file) {
	const m = readJson(file);
	const v = pkg.version.split('.').map(Number);
	m.header.version = v;
	for (const mod of m.modules) mod.version = v;
	for (const d of m.dependencies || []) {
		if (d.module_name) {
			d.version = pkg.devDependencies[d.module_name];
			if (!d.version) fail(`${file} asks for ${d.module_name}, which package.json doesn't pin`);
		} else if (d.uuid) d.version = v;
	}
	return m;
}

function build() {
	const java = javaRepo({ dir: opt('--java', null), ref: opt('--ref', undefined) });
	console.log(`Java edition: ${java.repo} at ${java.commit.slice(0, 10)}`);
	const gen = javaGenerator(java);
	const all = templates(gen);

	fs.rmSync(out, { recursive: true, force: true });
	const bp = path.join(out, 'bp'), bpTest = path.join(out, 'bp-test');
	fs.cpSync(path.join(root, 'packs', 'bp'), bp, { recursive: true });
	writeJson(path.join(bp, 'manifest.json'), manifest(path.join(root, 'packs', 'bp', 'manifest.json')));
	writeJson(path.join(bpTest, 'manifest.json'), manifest(path.join(root, 'test', 'manifest.json')));
	writeFile(path.join(bp, 'pack_icon.png'), java.read(`${ASSETS}icon.png`));

	// One structure file per wood and palette, and the lists the scripts import.
	const states = new Map(), mapping = new Map();
	const expected = {};
	for (const t of all) {
		if (t.skipped.length) fail(`${t.name}: ${t.skipped.length} blocks have no Bedrock form: ${t.skipped.map((s) => s.state).join(', ')}`);
		writeFile(path.join(bp, 'structures', 'spawn_gazebo', t.name + '.mcstructure'), mcstructure(SIZE, t.blocks));
		expected[t.name] = t.blocks.map((b) => [b.x, b.y, b.z, b.name]);
		for (const b of t.blocks) states.set(b.name + JSON.stringify(b.states), [b.name, b.states]);
	}
	for (const palette of Object.keys(gen.PALETTES)) for (const wood of gen.WOODS) {
		for (const [, { state }] of gen.gazebo(wood, palette)) mapping.set(state, map(state));
	}
	const banner = '// Generated by tools/build.js from the Java edition\'s gazebo generator. Don\'t edit.\n';
	writeFile(path.join(root, 'src', 'templates.ts'), banner
		+ `export const HALF = ${(SIZE[0] - 1) / 2};\n`
		+ `export const WOODS: string[] = ${JSON.stringify(gen.WOODS)};\n`
		+ `export const TEMPLATES: Record<string, true> = ${JSON.stringify(Object.fromEntries(all.map((t) => [t.name, true])))};\n`);
	writeFile(path.join(root, 'test', 'expected.ts'), banner
		+ `export const EXPECTED: Record<string, [number, number, number, string][]> = ${JSON.stringify(expected)};\n`
		+ `export const STATES: [string, Record<string, unknown>][] = ${JSON.stringify([...states.values()])};\n`);
	writeFile(path.join(root, 'build', 'mapping.txt'), [...mapping].sort().map(([j, m]) => `${j}\n   -> ${m.name} ${JSON.stringify(m.states)}${m.entity ? ' ' + JSON.stringify(m.entity) : ''}`).join('\n') + '\n');

	const main = fs.readFileSync(path.join(root, 'src', 'main.ts'), 'utf8');
	if (!main.includes(`VERSION = "${pkg.version}"`)) fail(`src/main.ts VERSION isn't ${pkg.version}`);

	// Scripts: TypeScript to JavaScript.
	const tsc = path.join(root, 'node_modules', 'typescript', 'bin', 'tsc');
	if (!fs.existsSync(tsc)) fail('TypeScript is not installed: run npm install');
	fs.rmSync(path.join(root, 'build', 'js'), { recursive: true, force: true });
	cp.execFileSync(process.execPath, [tsc, '-p', path.join(root, 'tsconfig.json')], { stdio: 'inherit' });
	fs.cpSync(path.join(root, 'build', 'js', 'src'), path.join(bp, 'scripts'), { recursive: true });
	fs.cpSync(path.join(root, 'build', 'js', 'test'), path.join(bpTest, 'scripts'), { recursive: true });

	// The .mcaddon: the behaviour pack in its own folder.
	const files = [];
	(function walk(d) {
		for (const e of fs.readdirSync(d, { withFileTypes: true }).sort((x, y) => (x.name < y.name ? -1 : 1))) {
			const p = path.join(d, e.name);
			if (e.isDirectory()) walk(p);
			else files.push({ name: 'SpawnGazebo_BP/' + path.relative(bp, p).split(path.sep).join('/'), data: fs.readFileSync(p) });
		}
	})(bp);
	const addon = path.join(root, 'dist', `SpawnGazebo-${pkg.version}.mcaddon`);
	writeFile(addon, zip(files));
	console.log(`built: ${all.length} gazebos; ${path.relative(root, addon)} (${files.length} files, ${Math.round(fs.statSync(addon).size / 1024)} KB)`);
}

build();
